/**
 * The 36 avatars of the avatar expansion and what earns each one. Every avatar is unlocked by an EXISTING achievement (the achievement ids are shipped and append-only), so the unlock is retroactive
 * with no migration: `settleAchievements` already records an achievement for a veteran whose counters pass its goal, and `unlockedAvatarIds` derives the avatar from the earned list. A veteran who
 * already reached the Castle level 15, a rebirth ladder tier, a Bestiary tier or a biome sees those faces unlocked the next time the Avatar window opens; nobody has to claim anything.
 *
 * Three sets, shown as their own tabs in the Avatar window: **heroes** (the gold-framed portraits, growth and craft milestones), **fiends** (monsters and villains, biome, boss and loss milestones) and **void** (the purple
 * endgame faces: top rebirth, Ember, boss and Bestiary tiers). Each entry may also add a **title** to its achievement (only when that achievement has none) so the new face comes with a name to wear next to it.
 * Ids are append-only (`tests/fixtures/saves/released-ids.json`): add at the end, never reorder or remove.
 *
 * @category Progression/Avatars
 * @order 5
 */
export type AvatarGroup = 'class' | 'heroes' | 'fiends' | 'void' | 'special';

export interface AvatarUnlockDef {
	id: string;
	name: string;
	group: Exclude<AvatarGroup, 'class' | 'special'>;
	/** Shipped achievement id that unlocks it */
	achievement: string;
	/** Shown on the locked card */
	how: string;
	/** File name (no extension) in `public/pixel/ui/heroes/` */
	portrait: string;
	bio: string;
	/** Title added to the achievement (ignored when the achievement already has one) */
	title?: { id: string; name: string };
}

