import type { BuffFamily, BuffStat } from '@/catalog/buffs';
import type { ItemDef } from '@/types/game';

/** A timed-buff elixir: one effect of one buff family, a bag stack, drunk by hand */
const elixir = (
	id: string,
	name: string,
	family: BuffFamily,
	stat: BuffStat,
	amount: number,
	durationSec: number,
	rarity: ItemDef['rarity'],
	sellValue: number,
	icon: ItemDef['icon'],
	flavour: string,
): ItemDef => ({
	id,
	name,
	kind: 'consumable',
	rarity,
	tier: 0,
	effects: [{ kind: 'buff', family, stat, amount, durationSec }],
	stackMax: 100,
	sellValue,
	icon,
	description: `${flavour} Drunk by hand; a second one of the same kind refreshes the first.`,
});

