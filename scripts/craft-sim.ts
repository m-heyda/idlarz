// Craft simulator (first version): what each recipe costs against what it is worth, and how fast the crafting level moves.
//   npm run craft-sim             print the tables
//   npm run craft-sim -- --md     also write docs/generated/craft-sim.md
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ITEM_CATALOG } from '../src/catalog';
import { COMPONENTS, RECIPES } from '../src/catalog/recipes';
import { RESOURCES } from '../src/catalog/resources';
import { CRAFTING } from '../src/config/crafting';
import { HARD_LIMITS } from '../src/config/limits';
import { craftCumulativeXp, craftLimit, craftTimeSec, recipeCostGold } from '../src/lib/crafting';

const WRITE_MD = process.argv.includes('--md');
const lines: string[] = [];
const out = (s = '') => lines.push(s);
const g = (n: number) => (Number.isInteger(n) ? String(n) : n.toFixed(1));

const inputText = (r: (typeof RECIPES)[number]) =>
	r.inputs.map((i) => ('resource' in i ? `${i.qty} ${RESOURCES[i.resource].label}` : `${i.qty} ${COMPONENTS[i.component].name}`)).join(' + ');

out('# Craft simulation');
out();
out('Generated by `npm run craft-sim -- --md`. Do not edit by hand. Design: [plan/crafting-v0.md](plan/crafting-v0.md).');
out();
out('## Recipes');
out();
out(
	'Cost is the gold value of the inputs at the merchant prices (a Glass Vial counts at what it costs to make). A crafted potion must cost less than the shop price and more than its sell value (tests/crafting).',
);
out();
out('| Recipe | Kind | Unlock | Inputs | Cost (gold value) | Sell value | Shop price | Cost / shop | Crafting XP | Cost per XP |');
out('|---|---|---:|---|---:|---:|---:|---:|---:|---:|');
for (const r of RECIPES) {
	const cost = recipeCostGold(r) / r.output.qty;
	const def = 'item' in r.output ? ITEM_CATALOG[r.output.item] : undefined;
	const sell = def?.sellValue;
	const shop = def?.shop;
	out(
		`| ${r.name} | ${r.kind} | ${r.unlock} | ${inputText(r)} | ${g(cost)} | ${sell ?? '-'} | ${shop ?? '-'} | ${shop ? `${Math.round((cost / shop) * 100)}%` : '-'} | ${r.xp} | ${g(cost / r.xp)} |`,
	);
}
out();
out('## Crafting level');
out();
out('Total crafting XP to reach a level, and how many crafts of the cheapest XP-per-gold recipe that is.');
out();
const best = RECIPES.reduce((a, b) => (recipeCostGold(a) / a.xp <= recipeCostGold(b) / b.xp ? a : b));
out(`Reference recipe: ${best.name} (${g(recipeCostGold(best) / best.xp)} gold per XP).`);
out();
out('| Level | Total XP | Crafts of the reference recipe | Gold value of the inputs |');
out('|---:|---:|---:|---:|');
for (const level of [2, 5, 10, 20, 30, 45, 60, 80, 100]) {
	const xp = craftCumulativeXp(level);
	const crafts = Math.ceil(xp / best.xp);
	out(
		`| ${level} | ${Math.round(xp).toLocaleString('en')} | ${crafts.toLocaleString('en')} | ${Math.round(crafts * recipeCostGold(best)).toLocaleString('en')} |`,
	);
}
out();
out(`Maximum level ${CRAFTING.maxLevel}; at most ${craftLimit('craftBatchCap')} crafts per batch (hard ceiling ${HARD_LIMITS.craftBatchCap}).`);

out();
out('## Timed batches');
out();
out(
	'Every recipe with a `timeSec` runs in the server-side queue (docs/plan/crafting-v0.md, Timed batch queue). Per hour of a batch running without a pause. Gold burned is the gold value of the whole input chain (a potion includes its vial) at merchant prices.',
);
out();
out('| Recipe | Seconds each | Items / hour | XP / hour | Gold burned / hour | Batch of the cap (minutes) | Batch of the hard ceiling (hours) |');
out('|---|---:|---:|---:|---:|---:|---:|');
const timed = RECIPES.filter((r) => r.timeSec);
for (const r of timed) {
	const sec = craftTimeSec(r);
	const crafts = 3600 / sec;
	out(
		`| ${r.name} | ${g(sec)} | ${Math.round(crafts * r.output.qty).toLocaleString('en')} | ${Math.round(crafts * r.xp).toLocaleString('en')} | ${Math.round(crafts * recipeCostGold(r)).toLocaleString('en')} | ${g((craftLimit('craftBatchCap') * sec) / 60)} | ${g((HARD_LIMITS.craftBatchCap * sec) / 3600)} |`,
	);
}
out();
out('## Trade goods income');
out();
out(
	'Gold from selling crafted trade goods (IDL-227) against the gold per second of the sim profiles. A good sells for at most 1.4x its inputs, and a queue only makes so many per hour, so goods stay a small side income: the gate is at most `GOODS_SHARE_MAX` of income. Income is the lowest gold per second a profile is expected to have at castle 10 (`MAGNITUDE_BANDS.gpsRun1Castle10` in scripts/sim.ts), which is the most favourable case for the goods; gold from selling the goods is counted gross (the raw inputs would also have sold).',
);
out();
const goods = RECIPES.filter((r) => r.kind === 'good');
const queues = [
	{ label: 'base limits (1 queue, speed 1)', slots: craftLimit('craftQueueSlots'), speed: craftLimit('craftSpeed') },
	{ label: 'hard ceilings (5 queues, speed 4)', slots: HARD_LIMITS.craftQueueSlots, speed: HARD_LIMITS.craftSpeed },
];
out('| Good | Unlock | Inputs | Input value | Sell value | Sell / input | Gold / hour in one queue |');
out('|---|---:|---|---:|---:|---:|---:|');
let bestGood = 0;
for (const r of goods) {
	const cost = recipeCostGold(r) / r.output.qty;
	const sell = ITEM_CATALOG[(r.output as { item: string }).item].sellValue;
	const perHour = (3600 / craftTimeSec(r)) * r.output.qty * sell;
	bestGood = Math.max(bestGood, perHour);
	out(`| ${r.name} | ${r.unlock} | ${inputText(r)} | ${g(cost)} | ${sell} | ${(sell / cost).toFixed(2)} | ${Math.round(perHour).toLocaleString('en')} |`);
}
out();
const GOODS_SHARE_MAX = 0.1;
const INCOME_GPS = 3000;
out('| Queues | Best good, gold / hour | Gold / second | Share of income (castle 10, 3,000 gold/s) | Gate |');
out('|---|---:|---:|---:|---|');
let gateFailed = false;
for (const q of queues) {
	const perHour = bestGood * q.slots * q.speed;
	const share = perHour / 3600 / INCOME_GPS;
	const pass = share <= GOODS_SHARE_MAX;
	gateFailed ||= !pass;
	out(
		`| ${q.label} | ${Math.round(perHour).toLocaleString('en')} | ${g(perHour / 3600)} | ${(share * 100).toFixed(1)}% | ${pass ? 'ok' : `**over ${GOODS_SHARE_MAX * 100}%**`} |`,
	);
}
out();
out('## Hours per level');
out();
out(
	'Crafting nonstop, always the recipe with the most XP per hour among those unlocked. A level also needs the materials; the gold burned is what that costs at merchant prices.',
);
out();
out('| Reached level | Hours for this level | Hours in total | Gold burned in total | Recipe used |');
out('|---:|---:|---:|---:|---|');
const xph = (r: (typeof timed)[number]) => (3600 / craftTimeSec(r)) * r.xp;
let totalHours = 0;
let totalGold = 0;
for (let level = 1; level < CRAFTING.maxLevel; level++) {
	const open = timed.filter((r) => r.unlock <= level);
	if (open.length === 0) break;
	const pick = open.reduce((a, b) => (xph(a) >= xph(b) ? a : b));
	const step = craftCumulativeXp(level + 1) - craftCumulativeXp(level);
	totalHours += step / xph(pick);
	totalGold += (step / pick.xp) * recipeCostGold(pick);
	if ([2, 5, 10, 20, 30, 45, 60, 80].includes(level + 1))
		out(
			`| ${level + 1} | ${g(Math.round((step / xph(pick)) * 100) / 100)} | ${g(Math.round(totalHours * 10) / 10)} | ${Math.round(totalGold).toLocaleString('en')} | ${pick.name} |`,
		);
}
out();
out(
	`Crafting nonstop, level ${CRAFTING.maxLevel} would take about ${Math.round(totalHours).toLocaleString('en')} hours of batches; the materials, not the clock, are the limit long before that.`,
);

console.log(lines.join('\n'));
if (WRITE_MD) {
	const path = resolve(__dirname, '..', 'docs', 'generated', 'craft-sim.md');
	writeFileSync(path, lines.join('\n') + '\n');
	console.log(`wrote ${path}`);
}
