/**
 * Generates docs/generated/balance-tables.md from the REAL game config + utils,
 * so the documentation can be regenerated after any tuning change.
 *
 *   npm run report        (= npx tsx scripts/balance-report.ts)
 *
 * Pacing (how long a player needs) comes from the bot simulation: npm run sim -> docs/generated/sim-milestones.md
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import {
	ANIMALS,
	BASE_GENERATION_RATES,
	LEVELING,
	BIOME_YIELD,
	BIOMES,
	BUILDING_COST,
	CASTLE_BASE_RATES,
	CASTLE_UPGRADE,
	CHARACTER_STAT_CONFIG,
	CLICK_LADDER,
	FARM,
	FARM_UPGRADES,
	type FarmUpgradeId,
	MERCHANT_SHOP_ITEMS,
	MERCHANT_UPGRADES,
	type MerchantUpgradeId,
	EMBER_UPGRADES,
	REBIRTH,
	type EmberUpgradeId,
	INITIAL_CHARACTER_STATS,
	MERCHANT_BUY_MULTIPLIER,
	MERCHANT_RESOURCE_PRICES,
	TILE_RESOURCE_COST,
	TILE_PRICE,
	RESOURCE_CAP,
	SCALING_CONFIG,
	XP_TILE,
} from '../src/config/gameConfig';
import {
	calculateAnimalCost,
	calculateAnimalProduction,
	calculateCombatStats,
	calculateResourceRates,
	calculateStatResourceModifiers,
	calculateTileCost,
	buildingCostFactor,
	calculateXpGain,
	castleModifier,
	createInitialWorld,
	farmUpgradeCost,
	merchantUpgradeCost,
	emberGain,
	emberUpgradeCost,
	cumulativeXp,
	xpToNextLevel,
} from '../src/utils/gameUtils';
import { ITEM_CATALOG } from '../src/config/itemCatalog';
import { formatTime } from '../src/utils/formatters';
import { mulberry32 } from '../src/lib/rng';
import type { Resources } from '../src/types/game';

const out: string[] = [];
const line = (s = '') => out.push(s);

const fmt = (n: number): string => {
	if (!isFinite(n)) return '∞';
	const a = Math.abs(n);
	if (a >= 1e24) return n.toExponential(2).replace('e+', 'e');
	const big = ['Sx', 'Qi', 'Qa', 'T'].find((_, i) => a >= Math.pow(10, 21 - 3 * i));
	if (big) return `${(n / Math.pow(10, 21 - 3 * ['Sx', 'Qi', 'Qa', 'T'].indexOf(big))).toFixed(2)}${big}`;
	if (a >= 1e9) return `${(n / 1e9).toFixed(2)}B`;
	if (a >= 1e6) return `${(n / 1e6).toFixed(2)}M`;
	if (a >= 1e4) return `${(n / 1e3).toFixed(2)}K`;
	if (a < 100) return n.toFixed(2);
	return n.toFixed(0);
};

const duration = (s: number): string => {
	if (!isFinite(s)) return '∞';
	if (s < 90) return `${s.toFixed(0)}s`;
	if (s < 5400) return `${(s / 60).toFixed(1)}m`;
	if (s < 172800) return `${(s / 3600).toFixed(1)}h`;
	return `${(s / 86400).toFixed(1)}d`;
};

const table = (head: string[], rows: (string | number)[][]) => {
	line(`| ${head.join(' | ')} |`);
	line(`| ${head.map(() => '---').join(' | ')} |`);
	rows.forEach((r) => line(`| ${r.join(' | ')} |`));
	line();
};

const RES = ['gold', 'wood', 'stone', 'coal', 'food', 'meat'] as const;

line('# Generated balance tables');
line();
line('> Generated by `npm run report` from the real config/utils. Do not edit by hand. Pacing: see [sim-milestones.md](sim-milestones.md).');
line();

// ---------------------------------------------------------------------------
line('## 1. Tile cost');
line();
line(
	'`n` = tiles owned *before* the purchase (the castle counts, so the first purchase is n = 1). ' +
		'Costs are with the starting Charisma (5 -> 2.5% discount). Extra resources are required from the tile counts in `TILE_RESOURCE_COST`. ' +
		'XP is before the XP-gain multiplier. The biome of every purchase is rolled (there is no biome picker).'
);
line();
{
	const rows: (string | number)[][] = [];
	let cumulative = 0;
	for (let n = 1; n <= 70; n++) {
		const c = calculateTileCost(n, 2.5);
		cumulative += c.gold;
		const extras = TILE_RESOURCE_COST.filter((r) => n >= r.from)
			.map((r) => `${fmt(c.resources[r.resource] ?? 0)} ${r.resource}`)
			.join(', ');
		rows.push([n, fmt(c.gold), fmt(cumulative), extras || '—', fmt(calculateXpGain(n + 1))]);
	}
	table(['n', 'gold', 'cumulative gold', 'extra resources', 'XP gained'], rows);

	line('### Late tiles (the polynomial tail)');
	line();
	line(
		`Past ${TILE_PRICE.tailFrom} tiles the price grows like (n / ${TILE_PRICE.tailFrom})^${TILE_PRICE.tailExponent} instead of ×${SCALING_CONFIG.growthEndgame} per tile, capped at ${TILE_PRICE.ceiling.toExponential(0).replace('e+', 'e')}; ` +
			`XP per tile has the same shape past ${XP_TILE.growthUntil} tiles (exponent ${XP_TILE.tailExponent}). Knobs: \`TILE_PRICE\`, \`XP_TILE\`, \`RESOURCE_CAP\` (${fmt(RESOURCE_CAP)}). See docs/05 BL16.`
	);
	line();
	const late: (string | number)[][] = [];
	let sum = 0;
	let from = 1;
	for (const n of [100, 157, 300, 1000, 3000, 10_000, 30_000, 50_000]) {
		for (; from < n; from++) sum += calculateTileCost(from, 2.5).gold;
		const c = calculateTileCost(n, 2.5);
		late.push([n, fmt(c.gold), fmt(sum + c.gold), fmt(calculateXpGain(n + 1))]);
		sum += c.gold;
		from = n + 1;
	}
	table(['n', 'gold', 'cumulative gold', 'XP gained'], late);
}

// ---------------------------------------------------------------------------
line('## 2. Level curve');
line();
line(`The level curve is written as anchors (total XP to reach a level): ${LEVELING.anchors.map(([l, x]) => `level ${l} = ${fmt(x)}`).join(', ')}; between two anchors every step is a constant factor bigger than the one before (\`xpToNextLevel\`). Soft cap at level ${LEVELING.softCapLevel}, maximum level ${LEVELING.maxLevel}. One attribute point per level, plus ${LEVELING.earlyBonusPoints} more for levels 2-${LEVELING.earlyBonusUntil}. Level, XP and attributes carry over a rebirth.`);
line();
{
	const rows: (string | number)[][] = [];
	let cumulative = 0;
	for (const L of [1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 25, 30, 40, 50, 60, 70, 79, 80, 85, 90, 95, 99]) {
		cumulative = cumulativeXp(L + 1);
		rows.push([L, fmt(xpToNextLevel(L)), fmt(cumulative)]);
	}
	table(['Level', 'XP to next', 'cumulative XP to reach L+1'], rows);
}

// ---------------------------------------------------------------------------
line('## 3. Castle');
line();
line(
	`Resource modifier: +${CASTLE_UPGRADE.baseResourceMultiplier * 100}% at level 1, doubling each level up to level ${CASTLE_UPGRADE.doublingUntil}, then +${CASTLE_UPGRADE.lateLevelStep * 100}% per level (added to **every** resource). ` +
		`Flat XP: +${CASTLE_UPGRADE.xpBonus}/s per level above 1. Max level ${CASTLE_UPGRADE.maxLevel}; each upgrade is a timed build paid up front.`
);
line();
{
	const rows: (string | number)[][] = [];
	CASTLE_UPGRADE.upgradeCosts.slice(0, CASTLE_UPGRADE.maxLevel - 1).forEach((c, i) => {
		const from = i + 1;
		const cost = c as Partial<Resources>;
		rows.push([
			`${from} → ${from + 1}`,
			formatTime(CASTLE_UPGRADE.durationsSec[i]),
			`+${(castleModifier(from + 1) * 100).toFixed(0)}%`,
			...RES.map((k) => (cost[k] ? fmt(cost[k] as number) : '—')),
		]);
	});
	table(['Upgrade', 'Build time', 'Modifier after', ...RES], rows);
	line(
		`Total build time to level ${CASTLE_UPGRADE.maxLevel}: ${formatTime(CASTLE_UPGRADE.durationsSec.slice(0, CASTLE_UPGRADE.maxLevel - 1).reduce((a, b) => a + b, 0))} ` +
			`(to level 6: ${formatTime(CASTLE_UPGRADE.durationsSec.slice(0, 5).reduce((a, b) => a + b, 0))}).`
	);
	line();
}

// ---------------------------------------------------------------------------
line('## 4. Farm animals');
line();
line(
	'Every purchase adds one animal (production = `baseProduction × count`). Cost (food) of the N-th animal = `floor(baseCost × costScaling^(N-1))`. ' +
		`Payback = food cost × ${MERCHANT_RESOURCE_PRICES.food} gold ÷ (meat/s of one animal × ${MERCHANT_RESOURCE_PRICES.meat} gold), before castle/Plains/stat meat modifiers.`
);
line();
ANIMALS.forEach((a) => {
	line(`### ${a.name} (first ${fmt(a.baseCost)} food, ×${a.costScaling} each, +${a.baseProduction} meat/s each)`);
	line();
	const rows: (string | number)[][] = [];
	let cumFood = 0;
	for (let N = 1; N <= 20; N++) {
		const cost = calculateAnimalCost(a, N - 1);
		cumFood += cost;
		const marginal = calculateAnimalProduction(a, N) - calculateAnimalProduction(a, N - 1);
		const paybackS = (cost * MERCHANT_RESOURCE_PRICES.food) / (marginal * MERCHANT_RESOURCE_PRICES.meat);
		rows.push([N, fmt(cost), fmt(cumFood), fmt(calculateAnimalProduction(a, N)), duration(paybackS)]);
	}
	table(['Count', 'cost of this one (food)', 'cumulative food', 'meat/s total', 'payback'], rows);
});

line('### Farm products and upgrades');
line();
line(
	`The pen holds ${FARM.baseCap} animals per kind (+4 per Pen Expansion level). Every animal also yields a product; once sold it is worth about a third of its meat.`
);
line();
table(
	['Animal', 'product', 'per second each', 'sells for', 'gold/s each (sold)', 'meat gold/s each', 'share of meat'],
	ANIMALS.map((a) => {
		const price = MERCHANT_RESOURCE_PRICES[a.product.resource];
		const sold = a.product.perSec * price;
		return [
			a.name,
			a.product.resource,
			a.product.perSec,
			price,
			sold.toFixed(3),
			(a.baseProduction * MERCHANT_RESOURCE_PRICES.meat).toFixed(2),
			`${((sold / (a.baseProduction * MERCHANT_RESOURCE_PRICES.meat)) * 100).toFixed(0)}%`,
		];
	})
);
table(
	['Upgrade', 'effect per level', 'max level', 'cost of level 1', 'cost of the last level'],
	(Object.keys(FARM_UPGRADES) as FarmUpgradeId[]).map((id) => {
		const def = FARM_UPGRADES[id];
		const fmtCost = (c: Partial<Resources>) =>
			Object.entries(c)
				.map(([r, v]) => `${fmt(v as number)} ${r}`)
				.join(' + ');
		return [def.label, def.description(1), def.maxLevel, fmtCost(farmUpgradeCost(id, 0)), fmtCost(farmUpgradeCost(id, def.maxLevel - 1))];
	})
);

// ---------------------------------------------------------------------------
line('## 5. Biomes and buildings');
line();
line(`Per-second output of one tile before adjacency and modifiers (already multiplied by BIOME_YIELD.scale = ${BIOME_YIELD.scale}; the castle is not scaled).`);
line();
{
	const rows = Object.values(BIOMES).map((b) => [
		b.label,
		Object.entries(b.resourceGeneration)
			.map(([k, v]) => `${k} ${+((v as number) * (b.name === 'castle' ? 1 : BIOME_YIELD.scale)).toFixed(3)}`)
			.join(', ') || '—',
	]);
	table(['Biome', 'Output per second'], rows);
	line(
		`Building cost: ${Object.entries(BUILDING_COST.base)
			.map(([r, v]) => `${fmt(v as number)} ${r}`)
			.join(', ')} as the base price. Building number n costs base × ${[0, 1, 2, 3, 4, 8, 16, 32].map((n) => `${n + 1}: ×${+buildingCostFactor(n).toFixed(2)}`).join(', ')} (first ${BUILDING_COST.starter.length} cheap, then ×${BUILDING_COST.growthEarly} for ${BUILDING_COST.earlyCount}, ×${BUILDING_COST.growthMid} for ${BUILDING_COST.midCount}, ×${BUILDING_COST.growthLate} after).`
	);
	line();
}

// ---------------------------------------------------------------------------
line('## 6. Stats');
line();
{
	const zero = { strength: 0, dexterity: 0, intelligence: 0, vitality: 0, charisma: 0 };
	const rows: (string | number)[][] = [];
	(Object.keys(zero) as (keyof typeof zero)[]).forEach((k) => {
		const m = calculateStatResourceModifiers({ ...INITIAL_CHARACTER_STATS, ...zero, [k]: 1 });
		rows.push([
			k,
			Object.entries(m)
				.filter(([, v]) => v > 0)
				.map(([r, v]) => `${r} +${(v * 100).toFixed(2)}%`)
				.join(', '),
		]);
	});
	table(['Stat (1 point)', 'Resource modifiers'], rows);
	line(
		`Charisma tile discount: ${CHARACTER_STAT_CONFIG.tileDiscountPercentPerCharisma}% per point, capped at ${CHARACTER_STAT_CONFIG.tileDiscountCapPercent}%.`
	);
	line();
	const c = calculateCombatStats(INITIAL_CHARACTER_STATS);
	line('Derived stats for the starting stats (all 5):');
	line();
	table(
		['Stat', 'calculateCombatStats()', 'INITIAL_CHARACTER_STATS'],
		Object.entries(c).map(([k, v]) => [k, String(v), String(INITIAL_CHARACTER_STATS[k as keyof typeof INITIAL_CHARACTER_STATS])])
	);
}

// ---------------------------------------------------------------------------
line('## 7. Rates of a brand-new game');
line();
line('A real game rolls its 8 start tiles at random; this table uses one fixed ring (seed 1) so the file is reproducible.');
line();
{
	const r = calculateResourceRates(createInitialWorld(mulberry32(1)), INITIAL_CHARACTER_STATS, {});
	const keys = Object.keys(r.total) as (keyof Resources)[];
	table(
		['Resource', 'BASE_GENERATION_RATES', 'CASTLE_BASE_RATES', 'base (computed)', 'modifier (computed)', 'total /s'],
		keys.map((k) => [
			k,
			BASE_GENERATION_RATES[k],
			CASTLE_BASE_RATES[k],
			r.base[k].toFixed(3),
			`${(r.modifiers[k] * 100).toFixed(1)}%`,
			r.total[k].toFixed(3),
		])
	);
}

// ---------------------------------------------------------------------------
line('## 8. Click power and merchant');
line();
table(
	['Level', 'gold per click (x gold/s)', 'price'],
	CLICK_LADDER.map((l, i) => [i, `${(l.power * 100).toFixed(0)}%`, l.price ? fmt(l.price) : '(start)'])
);
table(
	['Resource', 'sells for', `costs (x${MERCHANT_BUY_MULTIPLIER})`],
	Object.entries(MERCHANT_RESOURCE_PRICES).map(([r, p]) => [
		r,
		p,
		(['wood', 'stone', 'coal', 'food', 'meat'] as string[]).includes(r) ? p * MERCHANT_BUY_MULTIPLIER : 'not for sale',
	])
);
line('### Merchant bonuses and gear shop');
line();
table(
	['Bonus', 'effect per level', 'max level', 'price of level 1', 'price of the last level'],
	(Object.keys(MERCHANT_UPGRADES) as MerchantUpgradeId[]).map((id) => {
		const def = MERCHANT_UPGRADES[id];
		return [def.label, def.description(1), def.maxLevel, fmt(merchantUpgradeCost(id, 0)), fmt(merchantUpgradeCost(id, def.maxLevel - 1))];
	})
);
table(
	['Item', 'rarity', 'sells for', 'shop price', 'shop / sell'],
	MERCHANT_SHOP_ITEMS.map(({ id, price }) => {
		const def = ITEM_CATALOG[id];
		return [def.name, def.rarity, def.sellValue, fmt(price), `${(price / def.sellValue).toFixed(1)}x`];
	})
);

// ---------------------------------------------------------------------------
line('## 9. Rebirth and Embers');
line();
line(
	`Rebirth needs castle level ≥ ${REBIRTH.minCastleLevel} and ≥ ${REBIRTH.minTiles} tiles. Embers = \`floor(${REBIRTH.gainScale} × (castle − 5) × sqrt(tiles / 10))\`; ` +
		`each point earned is +${REBIRTH.incomePerPoint * 100}% income for ever.`
);
line();
{
	const tilesList = [20, 30, 40, 50, 60, 80];
	table(
		['castle level', ...tilesList.map((n) => `${n} tiles`)],
		[6, 7, 8, 9, 10].map((c) => [c, ...tilesList.map((n) => emberGain(c, n))])
	);
	const ids = Object.keys(EMBER_UPGRADES) as EmberUpgradeId[];
	line('Shop (cost in points of the next level, by current level):');
	line();
	table(
		['upgrade', 'effect per level', 'max', ...[0, 1, 2, 3, 5, 9].map((l) => `cost at level ${l}`)],
		ids.map((id) => [
			EMBER_UPGRADES[id].label,
			id === 'provisions'
				? Object.entries(EMBER_UPGRADES.provisions.bundle).map(([r, v]) => `${fmt(v as number)} ${r}`).join(' + ')
				: `${EMBER_UPGRADES[id].effectPerLevel * 100}%`,
			EMBER_UPGRADES[id].maxLevel,
			...[0, 1, 2, 3, 5, 9].map((l) => emberUpgradeCost(id, l)),
		])
	);
}

const target = resolve(
	dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')),
	'../docs/generated/balance-tables.md'
);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target} (${out.length} lines)`);
