// Monster ladder: win rate of each gear tier against every monster at the levels it spawns at (docs/ROADMAP.md, enemy rework).
//   npm run monster-ladder            print the table
//   npm run monster-ladder -- --md    also write docs/generated/monster-ladder.md
// The server's own fight engine. The hero is a level 30 character with 25 points spent (12 Strength, 8 Vitality, 5 Dexterity) and auto-use
// (Heal and Stun) on, no potions. Gear is worn at the item level of the monster (drops come at the level of what they drop from), so the table
// shows which tier of gear a fight asks for, not whether a player has levelled it.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { STARTER_EQUIPMENT } from '../src/config/itemCatalog';
import { MONSTERS } from '../src/config/combatConfig';
import { atItemLevel, fullSet, simulateMany, spentCharacter } from './fightSim';
import { spawnLevelRange } from '../src/lib/monsters';
import type { Equipment, MonsterType } from '../src/types/game';

const RUNS = 40;
const LOADOUTS: { name: string; equipment: Equipment }[] = [
	{ name: 'starter', equipment: STARTER_EQUIPMENT },
	{ name: 'woodland + club', equipment: fullSet('woodland', 'wooden_club') },
	{ name: 'knight + mace', equipment: fullSet('knight', 'steel_mace') },
	{ name: 'obsidian + maul', equipment: fullSet('obsidian', 'obsidian_maul') },
	{ name: 'obsidian + titan maul', equipment: fullSet('obsidian', 'titan_maul') },
];

const HERO = spentCharacter({ strength: 12, vitality: 8, dexterity: 5 });
const lines: string[] = [];
const out = (s = '') => {
	console.log(s);
	lines.push(s);
};

out('# Monster ladder');
out();
out('Generated by `npm run monster-ladder -- --md`. Do not edit by hand.');
out();
out(
	`Win % of a gear tier (level 30 hero, 25 points spent, Heal and Stun on, gear at the monster's item level, ${RUNS} seeded fights per cell) against each monster at the lowest and the highest level it appears at in a castle level 1 and a castle level 8 world (+10 levels is the most it can grow afterwards, shown as "grown").`,
);
out();
out(`| Monster | Level | ${LOADOUTS.map((l) => l.name).join(' | ')} |`);
out(`|---|---|${LOADOUTS.map(() => '---').join('|')}|`);
// tuning without editing the config: --only=rimeWraith,bossWinterWyrm  --set=bossWinterWyrm.hp=8000  (field names of MonsterDef, spawnWindow.cap ...)
const arg = (name: string) => process.argv.filter((a) => a.startsWith(`--${name}=`)).map((a) => a.slice(name.length + 3));
for (const spec of arg('set')) {
	const [path, raw] = spec.split('=');
	const keys = path.split('.');
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	let target: any = MONSTERS;
	for (let i = 0; i < keys.length - 1; i++) target = target[keys[i]];
	target[keys[keys.length - 1]] = Number(raw);
}
const only = arg('only').flatMap((v) => v.split(','));
const types = (Object.keys(MONSTERS) as MonsterType[]).filter((type) => only.length === 0 || only.includes(type));
for (const type of types) {
	const def = MONSTERS[type];
	const early = spawnLevelRange(type, 1);
	const late = spawnLevelRange(type, 8);
	const rows: [string, number][] = [
		['castle 1', early.min],
		['castle 8', late.max],
		['grown', Math.min(late.max + 10, def.spawnWindow.cap + 10)],
	];
	for (const [label, level] of rows) {
		const cells = LOADOUTS.map(({ name, equipment }) => {
			const r = simulateMany(
				{ equipment: atItemLevel(equipment, level), monster: { type, level }, character: HERO, level: 30, autoUse: true },
				RUNS,
				`ladder-${type}-${level}-${name}`,
			);
			return `${Math.round(r.winRate * 100)}%`;
		});
		out(`| ${def.label} | ${level} (${label}) | ${cells.join(' | ')} |`);
	}
}

if (process.argv.includes('--md')) {
	const path = resolve(__dirname, '..', 'docs', 'generated', 'monster-ladder.md');
	writeFileSync(path, lines.join('\n') + '\n');
	console.log(`wrote ${path}`);
}
