// Monster ladder: win rate of each gear tier against every monster at the levels it spawns at (docs/plan/ROADMAP.md, enemy rework).
//   npm run monster-ladder            print the table
//   npm run monster-ladder -- --md    also write docs/generated/monster-ladder.md (and docs/generated/spawn-mix.md)
//   npm run monster-ladder -- --hero=1,5,10   only the spawn mix: what a hero of that level meets at castle 1 (see scripts/spawnMix.ts)
// The server's own fight engine. The hero is a level 30 character with 25 points spent (12 Strength, 8 Vitality, 5 Dexterity) and auto-use
// (Heal and Stun) on, no potions. Gear is worn at the item level of the monster (drops come at the level of what they drop from), so the table
// shows which tier of gear a fight asks for, not whether a player has levelled it.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { STARTER_EQUIPMENT } from '../src/config/itemCatalog';
import { MONSTERS } from '../src/config/combatConfig';
import { GRADE_INFO } from '../src/catalog/items/grades';
import { atItemLevel, fullSet, kit, simulateMany, spentCharacter } from '../src/lib/fightSim';
import { spawnLevelRange } from '../src/lib/monsters';
import type { Equipment, MonsterType } from '../src/types/game';
import { spawnMixLines } from './spawnMix';

const RUNS = 40;
// `minLevel`: a grade kit is never worn below its own item level window (its stats are authored at the window start)
const LOADOUTS: { name: string; equipment: Equipment; minLevel?: number }[] = [
	{ name: 'starter', equipment: STARTER_EQUIPMENT },
	{ name: 'G1 kit + club', equipment: { ...kit('G1', 'mace') }, minLevel: GRADE_INFO.G1.levels[0] },
	{ name: 'G2 kit + club', equipment: { ...kit('G2', 'mace') }, minLevel: GRADE_INFO.G2.levels[0] },
	{ name: 'G3 kit + mace', equipment: { ...kit('G3', 'mace') }, minLevel: GRADE_INFO.G3.levels[0] },
	{ name: 'obsidian (G6) + maul', equipment: fullSet('obsidian', 'obsidian_maul') },
	{ name: 'obsidian + titan maul', equipment: fullSet('obsidian', 'titan_maul') },
];

const argOf = (name: string) => process.argv.filter((a) => a.startsWith(`--${name}=`)).map((a) => a.slice(name.length + 3));
const heroLevels = argOf('hero').flatMap((v) => v.split(',').map(Number));
const mixLines = () => [
	'# Spawn mix by hero level',
	'',
	'Generated by `npm run monster-ladder -- --md`. Do not edit by hand.',
	'',
	'What a hero in the starter kit (points spent 60 % Strength, 40 % Vitality) meets at castle level 1 on land that owns all four biomes in equal parts: the share of 600 new spawns by the chance the hero has to beat them at the level they appear at. "uniform" is the old pick (every type with a free tile equally likely); "weighted" is the server now (offline/spawnWeights.ts: full weight for a 40-95 % chance, floor 0.1 for hopeless ones, level and growth capped near what the hero beats).',
	'',
	...spawnMixLines(heroLevels.length > 0 ? heroLevels : [1, 5, 10]),
];
if (heroLevels.length > 0) {
	const mix = mixLines();
	console.log(mix.join('\n'));
	if (process.argv.includes('--md')) writeFileSync(resolve(__dirname, '..', 'docs', 'generated', 'spawn-mix.md'), mix.join('\n') + '\n');
	process.exit(0);
}

const HERO = spentCharacter({ strength: 12, vitality: 8, dexterity: 5 });
const lines: string[] = [];
const out = (s = '') => {
	console.log(s);
	lines.push(s);
};

out('# Monster ladder');
out();
out('Generated by `npm run monster-ladder -- --md`. Do not edit by hand.');
out();
out(
	`Win % of a gear tier (level 30 hero, 25 points spent, Heal and Stun on, gear at the monster's item level, ${RUNS} seeded fights per cell) against each monster at the lowest and the highest level it appears at in a castle level 1 and a castle level 8 world (+10 levels is the most it can grow afterwards, shown as "grown").`,
);
out();
out(`| Monster | Level | ${LOADOUTS.map((l) => l.name).join(' | ')} |`);
out(`|---|---|${LOADOUTS.map(() => '---').join('|')}|`);
// tuning without editing the config: --only=rimeWraith,bossWinterWyrm  --set=bossWinterWyrm.hp=8000  (field names of MonsterDef, spawnWindow.cap ...)
const arg = argOf;
for (const spec of arg('set')) {
	const [path, raw] = spec.split('=');
	const keys = path.split('.');
	// eslint-disable-next-line @typescript-eslint/no-explicit-any
	let target: any = MONSTERS;
	for (let i = 0; i < keys.length - 1; i++) target = target[keys[i]];
	target[keys[keys.length - 1]] = Number(raw);
}
const only = arg('only').flatMap((v) => v.split(','));
const types = (Object.keys(MONSTERS) as MonsterType[]).filter((type) => only.length === 0 || only.includes(type));
for (const type of types) {
	const def = MONSTERS[type];
	const early = spawnLevelRange(type, 1);
	const late = spawnLevelRange(type, 8);
	const rows: [string, number][] = [
		['castle 1', early.min],
		['castle 8', late.max],
		['grown', Math.min(late.max + 10, def.spawnWindow.cap + 10)],
	];
	for (const [label, level] of rows) {
		const cells = LOADOUTS.map(({ name, equipment, minLevel = 0 }) => {
			const r = simulateMany(
				{ equipment: atItemLevel(equipment, Math.max(level, minLevel)), monster: { type, level }, character: HERO, level: 30, autoUse: true },
				RUNS,
				`ladder-${type}-${level}-${name}`,
			);
			return `${Math.round(r.winRate * 100)}%`;
		});
		out(`| ${def.label} | ${level} (${label}) | ${cells.join(' | ')} |`);
	}
}

if (process.argv.includes('--md')) {
	const path = resolve(__dirname, '..', 'docs', 'generated', 'monster-ladder.md');
	writeFileSync(path, lines.join('\n') + '\n');
	console.log(`wrote ${path}`);
	writeFileSync(resolve(__dirname, '..', 'docs', 'generated', 'spawn-mix.md'), mixLines().join('\n') + '\n');
}
