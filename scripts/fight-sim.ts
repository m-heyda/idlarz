// Fight balance table: loadouts x monsters, run through the server's own fight engine (src/lib/fightSim.ts -> src/lib/offline/fight.ts).
//   npm run fight-sim            print the tables
//   npm run fight-sim -- --md    also write docs/generated/fight-sim.md
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { STARTER_EQUIPMENT } from '../src/config/itemCatalog';
import { COMBAT, MONSTERS } from '../src/config/combatConfig';
import { GRADE_INFO, type Grade } from '../src/catalog/items/grades';
import { atItemLevel, freshCharacter, kit, simulateMany, spentCharacter } from '../src/lib/fightSim';
import { monsterStats } from '../src/lib/monsters';
import { armorOf, attacksPerSecond, damagePerHit, damagePerSecond, maxHp } from '../src/lib/combat';
import { aggregateStats } from '../src/lib/inventory';
import type { Equipment } from '../src/types/game';

const RUNS = 60;

/** A full kit of one grade of the ladder (the cells of catalog/items/ladder.ts), so the table survives a change of sets */
const gradeKit = (grade: Grade, weapon: Parameters<typeof kit>[1] = 'mace'): Equipment => kit(grade, weapon);

export const LOADOUTS: { name: string; equipment: Equipment }[] = [
	{ name: 'starter kit', equipment: STARTER_EQUIPMENT },
	{ name: 'G1 kit + mace', equipment: gradeKit('G1') },
	{ name: 'G2 kit + mace', equipment: gradeKit('G2') },
	{ name: 'G3 kit + mace', equipment: gradeKit('G3') },
	{ name: 'G3 kit + bow', equipment: gradeKit('G3', 'bow') },
	{ name: 'G4 kit + mace', equipment: gradeKit('G4') },
	{ name: 'G4 kit + bow', equipment: gradeKit('G4', 'bow') },
	{ name: 'G5 kit + mace', equipment: gradeKit('G5') },
	{ name: 'G6 kit + mace', equipment: gradeKit('G6') },
	{ name: 'G6 kit + bow', equipment: gradeKit('G6', 'bow') },
];

const MONSTER_ROWS = [
	{ label: 'Boar level 1', monster: { type: 'thistleBoar', level: 1 } },
	{ label: 'Boar level 5', monster: { type: 'thistleBoar', level: 5 } },
	{ label: 'Boar level 9', monster: { type: 'thistleBoar', level: 9 } },
	{ label: `Great Auroch (${MONSTERS.bossGreatAuroch.hp} HP, ${MONSTERS.bossGreatAuroch.timeLimitSec} s)`, monster: { type: 'bossGreatAuroch', level: 15 } },
] as const;

const lines: string[] = [];
const out = (s = '') => {
	console.log(s);
	lines.push(s);
};
const cell = (r: ReturnType<typeof simulateMany>, withHp = false) =>
	`${Math.round(r.winRate * 100)}%${r.winRate > 0 ? ` (${r.meanTimeSec.toFixed(0)}s${withHp ? `, ${Math.round(r.meanHpLeft * 100)}% HP` : ''})` : ''}`;

const character = freshCharacter();
out('# Fight simulation');
out();
out('Generated by `npm run fight-sim -- --md`. Do not edit by hand.');
out();
out(
	`The server's own fight engine (a tick of ${COMBAT.tickSec} s): the player swings at the weapon's attack speed, the monster at its own (boar ${MONSTERS.thistleBoar.attackSpeed}/s, Great Auroch ${MONSTERS.bossGreatAuroch.attackSpeed.toFixed(2)}/s), ${RUNS} fights per cell.`,
);
out('Cells: win % (mean seconds to win). The streams are seeded, so the table is reproducible. Nobody clicks: gear, attributes, potions and skills decide.');
out();
out('| Loadout | Damage/hit | Swings/s | DPS | Armor | Max HP | Crit % | Super % |');
out('|---|---|---|---|---|---|---|---|');
for (const { name, equipment } of LOADOUTS) {
	const a = aggregateStats(equipment);
	out(
		`| ${name} | ${damagePerHit(equipment, character)} | ${attacksPerSecond(equipment, character)} | ${damagePerSecond(equipment, character)} | ${armorOf(equipment, character)} | ${maxHp(character, equipment)} | ${(character.critChance + a.critChance).toFixed(1)} | ${(5 + a.superCrit).toFixed(0)} |`,
	);
}
out();
out('# No potions, no skills');
out();
out(`| Loadout | ${MONSTER_ROWS.map((m) => m.label).join(' | ')} |`);
out(`|---|${MONSTER_ROWS.map(() => '---').join('|')}|`);
for (const { name, equipment } of LOADOUTS) {
	out(
		`| ${name} | ${MONSTER_ROWS.map(({ monster }) => cell(simulateMany({ equipment, monster: { ...monster }, autoUse: false }, RUNS, `plain-${name}`))).join(' | ')} |`,
	);
}

// ---- attribute builds: what 25 spare points (about level 30) do ------------------------------------------------------------------
const BUILDS = [
	{ name: 'no points spent', spend: {} },
	{ name: 'warrior: +25 Strength', spend: { strength: 25 } },
	{ name: 'mage: +25 Intelligence', spend: { intelligence: 25 } },
	{ name: 'tank: +15 Vitality, +10 Dexterity', spend: { vitality: 15, dexterity: 10 } },
	{ name: 'balanced: +5 each', spend: { strength: 5, dexterity: 5, intelligence: 5, vitality: 5, charisma: 5 } },
];
const BUILD_GEAR = [
	{ name: 'G6 kit + mace (physical)', equipment: gradeKit('G6') },
	{ name: 'G6 kit + staff (magic)', equipment: gradeKit('G6', 'staff') },
];
out();
out('# Level 30 builds');
out();
out('The same fight with 25 spare attribute points spent as shown (bonuses count points above the starting 5). No potions, no skills. Win % (mean seconds).');
out();
out('| Build + gear | Damage/hit | Swings/s | Armor | Boar level 9 | Great Auroch |');
out('|---|---|---|---|---|---|');
for (const gear of BUILD_GEAR) {
	for (const build of BUILDS) {
		const hero = spentCharacter(build.spend);
		const rat = simulateMany(
			{ equipment: gear.equipment, monster: { type: 'thistleBoar', level: 9 }, character: hero, autoUse: false },
			RUNS,
			`b1-${build.name}`,
		);
		const king = simulateMany(
			{ equipment: gear.equipment, monster: { type: 'bossGreatAuroch', level: 15 }, character: hero, autoUse: false },
			RUNS,
			`b2-${build.name}`,
		);
		out(
			`| ${build.name}, ${gear.name} | ${damagePerHit(gear.equipment, hero)} | ${attacksPerSecond(gear.equipment, hero)} | ${Math.round(armorOf(gear.equipment, hero) * 10) / 10} | ${cell(rat)} | ${cell(king)} |`,
		);
	}
}

// ---- auto-use: potions, Heal and Stun by the fixed rules ----------------------------------------------------------------------
out();
out('# Auto-use (level 30)');
out();
out(
	`Auto-use drinks a potion below ${COMBAT.auto.potionBelowHpPct}% HP, casts Heal below ${COMBAT.auto.healBelowHpPct}% and Stun whenever it is ready; mana, cooldowns and the potion cooldown apply. Skills do no damage: they only move the line where gear stops being enough. Cells: win % (mean seconds, mean HP left at the end).`,
);
out();
out('| Loadout | Kit | Boar level 9 | Great Auroch |');
out('|---|---|---|---|');
for (const { name, equipment } of LOADOUTS.filter((l) => ['starter kit', 'G1 kit + mace', 'G3 kit + mace', 'G6 kit + mace'].includes(l.name))) {
	for (const kit of [
		{ label: 'nothing', level: 1, potions: [] as { id: string; qty: number }[], autoUse: false },
		{ label: 'Heal + Stun', level: 30, potions: [], autoUse: true },
		{ label: 'Heal + Stun + 5 greater potions', level: 30, potions: [{ id: 'potion_greater', qty: 5 }], autoUse: true },
	]) {
		const r = (monster: { type: 'thistleBoar' | 'bossGreatAuroch'; level: number }) =>
			cell(simulateMany({ equipment, monster, level: kit.level, potions: kit.potions, autoUse: kit.autoUse }, RUNS, `k-${name}-${kit.label}`), true);
		out(`| ${name} | ${kit.label} | ${r({ type: 'thistleBoar', level: 9 })} | ${r({ type: 'bossGreatAuroch', level: 15 })} |`);
	}
}

// ---- the Great Auroch by level -------------------------------------------------------------------------------------------------------
out();
out('# The Great Auroch by level');
out();
out(
	'A boss: level 15 to 25 when he appears (higher with the castle), up to +10 as he grows, armor, 8 % crits, 20 % Stun resistance. HP, attack and armor follow the item level curve. A grade kit is a full kit of one grade of the ladder (the cells of catalog/items/ladder.ts) worn at the boss level ("at the level") or at the start of its own window when that is higher; "behind" is the kit of the grade two below, at its window start. Win % (mean seconds). No skills, no potions.',
);
const BOSS_ROWS: { level: number; grade: Grade; behind: Grade }[] = [
	{ level: 15, grade: 'G2', behind: 'G1' },
	{ level: 25, grade: 'G3', behind: 'G1' },
	{ level: 35, grade: 'G4', behind: 'G2' },
	{ level: 45, grade: 'G5', behind: 'G3' },
];
out();
out('| Boss level | Loadout | Gear | Result |');
out('|---|---|---|---|');
for (const { level, grade, behind } of BOSS_ROWS) {
	const stats = monsterStats('bossGreatAuroch', level);
	for (const [kitGrade, label] of [
		[grade, 'at the level'],
		[behind, 'behind'],
	] as const) {
		const itemLevel = Math.max(label === 'behind' ? 1 : level, GRADE_INFO[kitGrade].levels[0]);
		const r = simulateMany(
			{ equipment: atItemLevel(gradeKit(kitGrade), itemLevel), monster: { type: 'bossGreatAuroch', level }, autoUse: false },
			RUNS,
			`boss-${kitGrade}-${level}`,
		);
		out(`| ${level} (${stats.maxHp} HP, armor ${Math.round(stats.armor)}) | ${kitGrade} kit + mace | ${label} | ${cell(r)} |`);
	}
}

if (process.argv.includes('--md')) {
	writeFileSync(resolve(__dirname, '..', 'docs', 'generated', 'fight-sim.md'), lines.join('\n') + '\n');
	console.log('wrote docs/generated/fight-sim.md');
}
