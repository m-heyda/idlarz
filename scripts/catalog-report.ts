// Writes docs/generated/item-catalog.md: every item, set and drop pool, straight from src/catalog (never edit that file by hand).
//   npm run catalog-report
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ITEMS, RARITIES, RARITY_ORDER, SETS, formatStat, formatStats, lootPool, shopItems } from '../src/catalog';
import { RESOURCES } from '../src/catalog/resources';
import type { DropSource, ItemDef } from '../src/types/game';

const lines: string[] = [];
const out = (s = '') => lines.push(s);

const stats = (def: ItemDef) =>
	Object.entries(def.stats ?? {})
		.map(([k, v]) => formatStat(k, v as number))
		.join(', ') || (def.consumable ? `heals ${def.consumable.healHp} HP` : '');
const drops = (def: ItemDef) =>
	(Object.entries(def.drops ?? {}) as [DropSource, { weight: number; minTier?: number; qty?: number }][])
		.map(([src, r]) => `${src}${r.minTier ? `@T${r.minTier}+` : ''}${r.qty ? ` x${r.qty}` : ''} (${r.weight})`)
		.join(', ');

out('# Item catalog');
out();
out('Generated by `npm run catalog-report` from `src/catalog`. Do not edit by hand.');
out();
out('## Rarities');
out();
out('| Rarity | Colour | Merchant pays | Glow |');
out('|---|---|---|---|');
for (const r of RARITY_ORDER) {
	const d = RARITIES[r];
	out(`| ${d.label} | \`${d.color}\` | ${d.sellValue} | ${d.glow.blur}px @ ${d.glow.alpha}${d.glow.pulse ? ', pulses' : ''} |`);
}

out();
out('## Sets');
out();
for (const set of Object.values(SETS)) {
	out(`### ${set.label} (${set.size} slots)`);
	out();
	for (const [n, bonus] of Object.entries(set.bonuses)) out(`- ${n} pieces: ${formatStats(bonus)}`);
	out();
	out(`Pieces: ${set.pieces.join(', ')}`);
	out();
}

out('## Items');
out();
out('| Item | Id | Kind | Tier | Rarity | Stats | Sells | Shop | Drops (weight) |');
out('|---|---|---|---|---|---|---|---|---|');
for (const def of ITEMS) {
	const type = def.weaponType ? `${def.kind} (${def.weaponType})` : def.kind;
	out(`| ${def.name} | \`${def.id}\` | ${type} | ${def.tier} | ${RARITIES[def.rarity].label} | ${stats(def)} | ${def.sellValue} | ${def.shop ?? ''} | ${drops(def)} |`);
}

out();
out('## Loot pools');
out();
for (const source of ['rat', 'ratKing', 'chest'] as const) {
	const tiers = source === 'rat' ? [1, 3, 4, 5] : [1];
	for (const tier of tiers) {
		const pool = lootPool(source, tier);
		const total = pool.reduce((s, e) => s + e.weight, 0);
		const share = new Map<string, number>();
		for (const e of pool) {
			const label = RARITIES[ITEMS.find((d) => d.id === e.id)!.rarity].label;
			share.set(label, (share.get(label) ?? 0) + e.weight / total);
		}
		out(`- **${source}${source === 'rat' ? ` tier ${tier}` : ''}**: ${pool.length} items; ${[...share].map(([k, v]) => `${k} ${(v * 100).toFixed(1)}%`).join(', ')}`);
	}
}

out();
out('## Merchant stock');
out();
for (const { id, price } of shopItems()) out(`- ${ITEMS.find((d) => d.id === id)!.name}: ${price} gold`);

out();
out('## Resources');
out();
out('| Resource | Label | Merchant buys at | Source |');
out('|---|---|---|---|');
for (const [key, def] of Object.entries(RESOURCES)) out(`| \`${key}\` | ${def.label} | ${'merchant' in def ? (def as { merchant: { price: number } }).merchant.price : ''} | ${def.source} |`);

writeFileSync(resolve(__dirname, '..', 'docs', 'generated', 'item-catalog.md'), lines.join('\n') + '\n');
console.log('wrote docs/generated/item-catalog.md');
