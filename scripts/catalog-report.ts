// Writes docs/generated/item-catalog.md: every item, set and drop pool, straight from src/catalog (never edit that file by hand).
//   npm run catalog-report
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { AFFIXES, ITEMS, LOOT_POOLS, LOOT_PROFILES, LOOT_SOURCES, RARITIES, RARITY_ORDER, SETS, formatStat, formatStats, shopItems } from '../src/catalog';
import { LOOT_DATA } from '../src/lib/loot/data';
import { resolveSourceLevel } from '../src/lib/loot/generate';
import { eligibleCandidates } from '../src/lib/loot/pools';
import { RESOURCES } from '../src/catalog/resources';
import type { ItemDef } from '../src/types/game';

const lines: string[] = [];
const out = (s = '') => lines.push(s);

const stats = (def: ItemDef) =>
	Object.entries(def.stats ?? {})
		.map(([k, v]) => formatStat(k, v as number))
		.join(', ') || (def.consumable ? `heals ${def.consumable.healHp} HP` : '');
const window = (def: ItemDef) => (def.minItemLevel !== undefined ? `${def.minItemLevel}-${def.maxItemLevel}` : '');
const where = (def: ItemDef) => (def.generation === 'named' ? (def.pools ?? []).join(', ') : def.generation === 'base' ? 'general pool' : '');

out('# Item catalog');
out();
out('Generated by `npm run catalog-report` from `src/catalog`. Do not edit by hand.');
out();
out('## Rarities');
out();
out('| Rarity | Colour | Affixes | Merchant pays (item level 1) | Glow |');
out('|---|---|---|---|---|');
for (const r of RARITY_ORDER) {
	const d = RARITIES[r];
	out(`| ${d.label} | \`${d.color}\` | ${d.minAffixes}-${d.maxAffixes} | ${d.sellValue} | ${d.glow.blur}px @ ${d.glow.alpha}${d.glow.pulse ? ', pulses' : ''} |`);
}

out();
out('## Sets');
out();
for (const set of Object.values(SETS)) {
	out(`### ${set.label} (${set.size} slots)`);
	out();
	for (const [n, bonus] of Object.entries(set.bonuses)) out(`- ${n} pieces: ${formatStats(bonus)}`);
	out();
	out(`Pieces: ${set.pieces.join(', ')}`);
	out();
}

out('## Items');
out();
out('Gear is authored at the start of its item level window; bases roll their rarity, named items have a fixed one.');
out();
out('| Item | Id | Kind | Tier | Type | Item levels | Stats at its first level | Shop | Drops from |');
out('|---|---|---|---|---|---|---|---|---|');
for (const def of ITEMS) {
	const type = def.weaponType ? `${def.kind} (${def.weaponType})` : def.kind;
	out(`| ${def.name} | \`${def.id}\` | ${type} | ${def.tier} | ${def.generation ?? 'consumable'}${def.fixedRarity ? ` (${RARITIES[def.fixedRarity as keyof typeof RARITIES].label})` : ''} | ${window(def)} | ${stats(def)} | ${def.shop ?? ''} | ${where(def)} |`);
}

out();
out('## Affixes');
out();
out('| Affix | Position | Stat | Needs item level | Fits |');
out('|---|---|---|---|---|');
for (const a of AFFIXES) out(`| ${a.name} | ${a.position} | ${a.stat} | ${a.minItemLevel} | ${a.tags.length ? a.tags.join(', ') : 'any gear'} |`);

out();
out('## Loot sources');
out();
out('Rarity chances are the profile weights normalised over the rarities that pass their item level gate; level is the item level at the source (castle level 1, tier 1-5 for rats).');
out();
for (const source of Object.values(LOOT_SOURCES)) {
	const profile = LOOT_PROFILES[source.lootProfileId];
	const tiers = source.id === 'rat' ? [1, 3, 5] : [1];
	for (const tier of tiers) {
		const level = resolveSourceLevel(source.level, tier, 1) + profile.itemLevel.offset;
		const weights = Object.entries(profile.rarityWeights).filter(([r, w]) => w > 0 && level >= (profile.rarityLevelGate?.[r] ?? 1));
		const total = weights.reduce((s, [, w]) => s + w, 0);
		const share = weights.map(([r, w]) => `${RARITIES[r as keyof typeof RARITIES].label} ${((w / total) * 100).toFixed(1)}%`).join(', ');
		const pool = profile.generalPoolId ? eligibleCandidates(LOOT_DATA, profile.generalPoolId, level).length : 0;
		out(`- **${source.id}${source.id === 'rat' ? ` tier ${tier}` : ''}** (profile \`${profile.id}\`, item level ${level}): ${pool} bases eligible; ${share}`);
	}
	for (const t of profile.bonusTables) out(`  - bonus \`${t.id}\` from pool \`${t.poolId}\`${t.chance !== undefined ? `, chance ${t.chance}` : ''}${t.placement ? `, ${t.placement}` : ''}`);
}
out();
out('Pools: ' + Object.values(LOOT_POOLS).map((p) => `\`${p.id}\``).join(', '));

out();
out('## Merchant stock');
out();
for (const { id, price } of shopItems()) out(`- ${ITEMS.find((d) => d.id === id)!.name}: ${price} gold`);

out();
out('## Resources');
out();
out('| Resource | Label | Merchant buys at | Source |');
out('|---|---|---|---|');
for (const [key, def] of Object.entries(RESOURCES)) out(`| \`${key}\` | ${def.label} | ${'merchant' in def ? (def as { merchant: { price: number } }).merchant.price : ''} | ${def.source} |`);

writeFileSync(resolve(__dirname, '..', 'docs', 'generated', 'item-catalog.md'), lines.join('\n') + '\n');
console.log('wrote docs/generated/item-catalog.md');
