// Loot simulator: seeded Monte Carlo over the real pipeline (src/lib/loot), per source and level. Use it to tune drop rates.
//   npm run loot-sim                 print the tables (100,000 kills per row)
//   npm run loot-sim -- --md         also write docs/generated/loot-sim.md
//   npm run loot-sim -- --kills 20000 --seed 7
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
	BIOME_LOOT,
	BOSS_LOOT,
	ITEM_CATALOG,
	LOOT_PROFILES,
	RARITIES,
	RARITY_ORDER,
	bossSourceId,
	buildBossLoot,
	monsterSourceId,
	type BossLootDef,
} from '../src/catalog';
import { COMBAT } from '../src/config/combatConfig';
import { gradeOfItem } from '../src/catalog/items/grades';
import { baseStatsAt } from '../src/lib/itemInstance';
import { generateLoot } from '../src/lib/loot/generate';
import { LOOT_DATA, type LootData } from '../src/lib/loot/data';
import { validateLootData } from '../src/lib/loot/validate';
import { mulberry32 } from '../src/lib/rng';
import { LUCK } from '../src/config/spawns';
import { BOSS_SET_CHANCE, BOSS_SET_PITY, BOSS_UNIQUE_CHANCE, BOSS_UNIQUE_PITY } from '../src/catalog/lootConfig';
import { chestIntervalSec, gemChance, goldenMonsterChance, rollGemFind } from '../src/lib/luck';

const arg = (name: string, fallback: number) => {
	const at = process.argv.indexOf(`--${name}`);
	return at >= 0 ? Number(process.argv[at + 1]) : fallback;
};
const KILLS = arg('kills', 100_000);
const SEED = arg('seed', 2026);
const WRITE_MD = process.argv.includes('--md');

interface Scenario {
	label: string;
	sourceId: string;
	level?: number;
	castleLevel?: number;
}

const SCENARIOS: Scenario[] = [
	{ label: 'Monster level 1', sourceId: 'monster', level: 1 },
	{ label: 'Monster level 5', sourceId: 'monster', level: 5 },
	{ label: 'Monster level 9', sourceId: 'monster', level: 9 },
	{ label: 'Monster level 15', sourceId: 'monster', level: 15 },
	{ label: 'Monster level 20', sourceId: 'monster', level: 20 },
	{ label: 'Boss (plains) level 15', sourceId: bossSourceId('plains'), level: 15 },
	{ label: 'Boss (forest) level 25', sourceId: bossSourceId('forest'), level: 25 },
	{ label: 'Boss (swamp) level 35', sourceId: bossSourceId('swamp'), level: 35 },
	{ label: 'Boss (tundra) level 45', sourceId: bossSourceId('tundra'), level: 45 },
	{ label: 'Chest, castle 1', sourceId: 'chest', castleLevel: 1 },
	{ label: 'Chest, castle 5', sourceId: 'chest', castleLevel: 5 },
	{ label: 'Chest, castle 10', sourceId: 'chest', castleLevel: 10 },
];

const pct = (n: number, d: number) => (d ? `${((n / d) * 100).toFixed(1)}%` : '-');
const percentile = (sorted: number[], p: number) => (sorted.length ? sorted[Math.min(sorted.length - 1, Math.floor(p * sorted.length))] : 0);
const HIGH_RANK = RARITIES.epic.order; // "high rarity" for the at-least-one metric: epic and up

const lines: string[] = [];
const out = (s = '') => lines.push(s);

const validation = validateLootData();
out('# Loot simulation');
out();
out(`Generated by \`npm run loot-sim -- --md\` (${KILLS.toLocaleString('en')} kills per row, seed ${SEED}). Do not edit by hand.`);
out();
out(`Config validation: ${validation.errors.length} errors, ${validation.warnings.length} warnings.`);
for (const e of validation.errors) out(`- ERROR ${e}`);
for (const w of validation.warnings) out(`- warning ${w}`);
out();

out('## Per source');
out();
out(
	'| Source | Source level | Gear / kill | ' +
		RARITY_ORDER.map((r) => RARITIES[r].label).join(' | ') +
		' | Item level p50 / p90 / max | P(epic+ per kill) | Named / kill | Empty-pool warnings |',
);
out('|---|---:|---:|' + RARITY_ORDER.map(() => '---:').join('|') + '|---|---:|---:|---:|');
for (const s of SCENARIOS) {
	const rng = mulberry32(SEED);
	const byRarity = new Map<string, number>();
	const levels: number[] = [];
	let gear = 0;
	let named = 0;
	let high = 0;
	let warnings = 0;
	let sourceLevel = 0;
	for (let i = 0; i < KILLS; i++) {
		const r = generateLoot({ sourceId: s.sourceId, level: s.level, castleLevel: s.castleLevel }, rng);
		sourceLevel = r.sourceLevel;
		warnings += r.warnings.length;
		let killHigh = false;
		for (const d of r.drops) {
			if (d.kind !== 'gear') continue;
			gear++;
			levels.push(d.item.level);
			byRarity.set(d.item.rarity, (byRarity.get(d.item.rarity) ?? 0) + 1);
			if (ITEM_CATALOG[d.item.base].generation === 'named') named++;
			if (LOOT_DATA.rarities[d.item.rarity].order >= HIGH_RANK) killHigh = true;
		}
		if (killHigh) high++;
	}
	levels.sort((a, b) => a - b);
	out(
		`| ${s.label} | ${sourceLevel} | ${(gear / KILLS).toFixed(3)} | ${RARITY_ORDER.map((r) => pct(byRarity.get(r) ?? 0, gear)).join(' | ')} | ${percentile(levels, 0.5)} / ${percentile(levels, 0.9)} / ${levels[levels.length - 1] ?? 0} | ${pct(high, KILLS)} | ${(named / KILLS).toFixed(4)} | ${warnings} |`,
	);
}

out();
out('## Bosses');
out();
out(
	`Each biome's boss drops from a source of its own (\`boss_<biome>\`, IDL-44): a guaranteed general roll, its potions, its unique (a named legendary weapon: ${(BOSS_UNIQUE_CHANCE * 100).toFixed(0)} % per kill, +${(BOSS_UNIQUE_PITY.perMiss * 100).toFixed(0)} % per miss up to +${(BOSS_UNIQUE_PITY.maxBonus * 100).toFixed(0)} %, a drop resets the counter) and, once one is wired, a piece of the set it owns. The kills below are bosses killed in a row, counted until the drop (${KILLS.toLocaleString('en')} runs per row, pity included); hours assume one boss kill per boss timer (\`COMBAT.spawn.bossIntervalSec\`, ${COMBAT.spawn.bossIntervalSec / 3600} h; only one boss stands at a time, so this is the best case of a player who kills every boss).`,
);
out();
out('| Boss | Level | Owns | Gear / kill | Kills to the drop: mean | p10 | p50 | p90 | Hours at 1 boss / timer (mean) |');
out('|---|---:|---|---:|---:|---:|---:|---:|---:|');
/** Kills in a row until a drop that satisfies `done`, with the pity counters carried between kills */
const killsUntil = (
	sourceId: string,
	level: number,
	runs: number,
	data: LootData,
	seed: number,
	step: (drops: ReturnType<typeof generateLoot>['drops'], owned: Set<string>) => boolean,
): number[] => {
	const rng = mulberry32(seed);
	const results: number[] = [];
	for (let i = 0; i < runs; i++) {
		let pity: Record<string, number> = {};
		const owned = new Set<string>();
		let kills = 0;
		for (;;) {
			kills++;
			const r = generateLoot({ sourceId, level, owned: [...owned], pity }, rng, data);
			pity = r.pity;
			if (step(r.drops, owned) || kills >= 10_000) break;
		}
		results.push(kills);
	}
	return results.sort((a, b) => a - b);
};
const summary = (kills: number[]) => {
	const mean = kills.reduce((a, b) => a + b, 0) / (kills.length || 1);
	return { mean, p10: percentile(kills, 0.1), p50: percentile(kills, 0.5), p90: percentile(kills, 0.9) };
};
const RUNS = Math.min(KILLS, 20_000);
const hours = (kills: number) => ((kills * COMBAT.spawn.bossIntervalSec) / 3600).toFixed(0);
for (const [biome, def] of Object.entries(BOSS_LOOT)) {
	const sourceId = bossSourceId(biome);
	const level = LOOT_DATA.sources[sourceId].levels!.max - 10;
	const rng = mulberry32(SEED);
	let gear = 0;
	for (let i = 0; i < KILLS; i++)
		gear += generateLoot({ sourceId, level }, rng).drops.filter((d) => d.kind === 'gear' && ITEM_CATALOG[d.item.base].generation !== 'named').length;
	for (const unique of def.uniques) {
		const k = summary(killsUntil(sourceId, level, RUNS, LOOT_DATA, SEED, (drops) => drops.some((d) => d.kind === 'gear' && d.item.base === unique)));
		out(
			`| ${sourceId} | ${level} | ${ITEM_CATALOG[unique].name} | ${(gear / KILLS).toFixed(2)} | ${k.mean.toFixed(1)} | ${k.p10} | ${k.p50} | ${k.p90} | ${hours(k.mean)} |`,
		);
	}
	if (!def.uniques.length) out(`| ${sourceId} | ${level} | nothing yet | ${(gear / KILLS).toFixed(2)} | - | - | - | - | - |`);
}
out();
out('### A full set from one boss (projection)');
out();
out(
	`No set of the four biomes has live pieces yet (\`BOSS_LOOT[biome].setId\` is null for all of them, the Obsidian set is out of item level reach and S1-S3 are disabled), so this is a projection on a copy of the data: the tundra boss owns Blightbound with its pieces made reachable. The set table triggers ${(BOSS_SET_CHANCE * 100).toFixed(0)} % per kill, +${(BOSS_SET_PITY.perMiss * 100).toFixed(0)} % per miss up to +${(BOSS_SET_PITY.maxBonus * 100).toFixed(0)} %, and gives one piece, missing pieces first (the player's bag and gear count as owned). Kills are bosses killed until the whole set is owned.`,
);
out();
out('| Pieces | Kills for the whole set: mean | p10 | p50 | p90 | Hours at 1 boss / timer (mean) | Hours (p90) |');
out('|---:|---:|---:|---:|---:|---:|---:|');
{
	const data = JSON.parse(JSON.stringify(LOOT_DATA)) as LootData;
	const loot: Record<string, BossLootDef> = Object.fromEntries(
		Object.entries(BOSS_LOOT).map(([b, d]) => [b, { ...d, setId: b === 'tundra' ? 'blightbound' : null }]),
	);
	const built = buildBossLoot(loot);
	Object.assign(data.pools, built.pools);
	Object.assign(data.profiles, built.profiles);
	Object.assign(data.sources, built.sources);
	const pieces = Object.values(data.items).filter((d) => d.set === 'blightbound');
	for (const d of pieces) Object.assign(d, { enabled: true, minItemLevel: 1, maxItemLevel: 100, dropLevels: undefined });
	const kills = killsUntil('boss_tundra', 40, RUNS, data, SEED, (drops, owned) => {
		for (const d of drops) if (d.kind === 'gear' && data.items[d.item.base].set) owned.add(d.item.base);
		return owned.size >= pieces.length;
	});
	const k = summary(kills);
	out(`| ${pieces.length} | ${k.mean.toFixed(1)} | ${k.p10} | ${k.p50} | ${k.p90} | ${hours(k.mean)} | ${hours(k.p90)} |`);
}

out();
out('## Per biome');
out();
out(
	'Normal monsters drop from the source of their biome (`monster_<biome>`, pool `equipment_<biome>`: ladder grades up to the ceiling of the biome; every piece that drops is on the ladder since IDL-243). Each row is a monster level inside the range of the biome: gear per kill, the grade mix of what dropped (`-` = a piece outside the ladder, none today) and the share of drops per slot kind. Only the live grades (G1-G3) have enabled items, so the ceilings above G3 change nothing yet.',
);
out();
out('| Source | Level | Gear / kill | Grades | Weapon | Off hand | Armor | Accessory |');
out('|---|---:|---:|---|---:|---:|---:|---:|');
const biomeRows = [
	...Object.entries(BIOME_LOOT).flatMap(([biome, { levels }]) =>
		[levels.min, Math.round((levels.min + levels.max) / 2), levels.max].map((level) => ({ id: monsterSourceId(biome), level })),
	),
	{ id: 'monster', level: 9 },
];
for (const row of biomeRows) {
	const rng = mulberry32(SEED);
	const grades = new Map<string, number>();
	const kinds = new Map<string, number>();
	let gear = 0;
	for (let i = 0; i < KILLS; i++) {
		for (const d of generateLoot({ sourceId: row.id, level: row.level }, rng).drops) {
			if (d.kind !== 'gear') continue;
			gear++;
			const def = ITEM_CATALOG[d.item.base];
			grades.set(gradeOfItem(def) ?? '-', (grades.get(gradeOfItem(def) ?? '-') ?? 0) + 1);
			kinds.set(def.kind, (kinds.get(def.kind) ?? 0) + 1);
		}
	}
	const gradeMix = [...grades.entries()]
		.sort()
		.map(([g, n]) => `${g} ${pct(n, gear)}`)
		.join(', ');
	out(
		`| ${row.id} | ${row.level} | ${(gear / KILLS).toFixed(3)} | ${gradeMix} | ${['weapon', 'offhand', 'armor', 'accessory'].map((k) => pct(kinds.get(k) ?? 0, gear)).join(' | ')} |`,
	);
}

out();
out('## What Luck does');
out();
out(
	'A level 9 monster and a castle 5 chest at several Luck totals (Charisma + Lucky Charm + gear). Gems and lucky monsters exist only for signed-in players (the server rolls them).',
);
out();
out(
	'| Luck | Chest every | Monster gear / kill | Rare+ share of monster gear | Rare+ share of chest gear | Gem find / chest | Gems / chest | Golden monster |',
);
out('|---:|---:|---:|---:|---:|---:|---:|---:|');
for (const luck of [0, 10, 30, 60, 100, 200]) {
	const share = (sourceId: string, level: number | undefined, castleLevel: number | undefined) => {
		const rng = mulberry32(SEED);
		let gear = 0;
		let rare = 0;
		for (let i = 0; i < KILLS; i++) {
			for (const d of generateLoot({ sourceId, level, castleLevel, luck }, rng).drops) {
				if (d.kind !== 'gear') continue;
				gear++;
				if (LOOT_DATA.rarities[d.item.rarity].order >= LUCK.rarityFromOrder) rare++;
			}
		}
		return { perKill: gear / KILLS, rare: pct(rare, gear) };
	};
	const monster = share('monster', 9, undefined);
	const chest = share('chest', undefined, 5);
	const rng = mulberry32(SEED + 1);
	let gems = 0;
	for (let i = 0; i < KILLS; i++) gems += rollGemFind(luck, rng);
	out(
		`| ${luck} | ${(chestIntervalSec(luck) / 60).toFixed(1)} min | ${monster.perKill.toFixed(3)} | ${monster.rare} | ${chest.rare} | ${(gemChance(luck) * 100).toFixed(1)}% | ${(gems / KILLS).toFixed(2)} | ${(goldenMonsterChance(luck) * 100).toFixed(1)}% |`,
	);
}

out();
out('## Item power over the level range');
out();
out(
	'Base stats of a few items at item level 1, 10, 25, 50, 100 (common, quality 50, no affixes), straight from the level curve. Items below their first level are shown at it.',
);
out();
const SAMPLE = ['wooden_sword', 'iron_sword', 'obsidian_blade', 'emberbrand', 'steel_cuirass'];
const LEVELS = [1, 10, 25, 50, 100];
out('| Item | ' + LEVELS.map((l) => `L${l}`).join(' | ') + ' |');
out('|---|' + LEVELS.map(() => '---').join('|') + '|');
for (const id of SAMPLE) {
	const def = ITEM_CATALOG[id];
	const primary = def.kind === 'weapon' ? 'damage' : 'armor';
	const cells = LEVELS.map((l) => {
		const level = Math.min(Math.max(l, def.minItemLevel ?? 1), def.maxItemLevel ?? 100);
		return `${level === l ? '' : '(' + level + ') '}${baseStatsAt(def, level, 50, RARITIES.common)[primary]}`;
	});
	out(`| ${def.name} (${primary}) | ${cells.join(' | ')} |`);
}

out();
out('## Profiles');
out();
for (const p of Object.values(LOOT_PROFILES)) {
	const total = Object.values(p.rarityWeights).reduce((a, b) => a + b, 0);
	out(
		`- **${p.id}**: ${p.rolls.min}-${p.rolls.max} roll(s), ${p.rolls.guaranteed ?? 0} guaranteed, ${(p.rolls.chancePerRoll * 100).toFixed(0)}% per roll; rarity weights ${Object.entries(
			p.rarityWeights,
		)
			.map(([r, w]) => `${r} ${((w / total) * 100).toFixed(1)}%`)
			.join(', ')}; bonus: ${p.bonusTables.map((t) => t.id).join(', ') || 'none'}`,
	);
}

console.log(lines.join('\n'));
if (WRITE_MD) {
	writeFileSync(resolve(__dirname, '..', 'docs', 'generated', 'loot-sim.md'), lines.join('\n') + '\n');
	console.log('\nwrote docs/generated/loot-sim.md');
}
